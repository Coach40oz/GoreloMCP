def test_every_ref_points_at_a_schema(index):
    names = set(index["schemas"])

    def refs(entry):
        if entry.get("ref"):
            yield entry["ref"]
        if isinstance(entry.get("items"), dict):
            yield from refs(entry["items"])

    for name, schema in index["schemas"].items():
        for field, entry in schema["fields"].items():
            for ref in refs(entry):
                assert ref in names, f"{name}.{field} -> {ref}"
    for key, op in index["ops"].items():
        body = op["body"]
        if body and body["schema"]:
            assert body["schema"] in names, key
        if op["response"]["schema"]:
            assert op["response"]["schema"] in names, key


