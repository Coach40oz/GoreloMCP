def raw_spec_link_problem(link):
    """Why `link` (backups/swagger-latest.json) cannot be read as the raw spec, or None when it can."""
    if link.is_symlink() and not link.exists():  # exists() follows the link, so it is False when the target is missing
        return f"{link.name} is a symlink to {link.readlink()}, which does not exist"
    if not link.exists():
        return f"{link.name} does not exist"
    if not link.is_file():
        return f"{link.name} is not a file"
    return None


def test_the_latest_raw_spec_is_in_the_repo_and_its_link_does_not_dangle():
    """backups/swagger-latest.json is a symlink to the newest raw spec. If a release is committed without the file
    that link names (a plain `git commit -a` leaves a new, untracked file out), the link dangles in every checkout and every
    test that reads the raw spec text is SKIPPED, not failed (they are marked skipif not LATEST_SPEC.exists()): drift between
    the tool texts and the published texts would then go unnoticed. So a dangling link is a failure here."""
    problem = raw_spec_link_problem(LATEST_SPEC)
    assert problem is None, (
        f"{problem}: commit that raw spec file with the release (git add backups/<file>); until then the tests that read "
        "the raw spec text are skipped, not run"
    )


def test_a_dangling_latest_link_is_reported_and_a_resolving_one_is_not(tmp_path):
    link = tmp_path / "swagger-latest.json"
    link.symlink_to("swagger-20990101-000000.json")  # relative, the way spec_snapshot.save_raw writes it; no such file yet
    assert link.is_symlink() and not link.exists()
    assert raw_spec_link_problem(link) == "swagger-latest.json is a symlink to swagger-20990101-000000.json, which does not exist"
    (tmp_path / "swagger-20990101-000000.json").write_text("{}", encoding="utf-8")  # the file is committed with the release
    assert link.exists() and raw_spec_link_problem(link) is None


def test_a_missing_latest_file_a_regular_one_and_a_directory_are_each_judged(tmp_path):
    path = tmp_path / "swagger-latest.json"
