# The one recorded attribute that is deliberately not diffed on its own: "method" is
# the first word of the op key, so a different method is a different (added or
# removed) op rather than a changed one.
UNDIFFED_ALONE = {("ops", "*", "method")}


def _attribute_shape(path):
    """The index layout position of a leaf: dynamic names (op, scheme, schema, param, field) become '*'.

    The name that follows "path_params", "query_params" or "fields" is a param or field
    name, however deeply an inline object nests, so nested fields get one shape per
    attribute too.
    """
    shape = []
    for position, part in enumerate(path):
        previous = path[position - 1] if position else None
        dynamic = (
            isinstance(part, int)
            or (position == 1 and path[0] in ("ops", "schemas", "security_schemes"))
            or previous in ("path_params", "query_params", "fields")
        )
        shape.append("*" if dynamic else part)
    return tuple(shape)


def _leaves(node, path=()):
    """Yield (path, value) for every scalar and every list in a JSON document."""
    if isinstance(node, dict):
        for key, value in node.items():
            yield from _leaves(value, (*path, key))
    elif isinstance(node, list):
        yield path, node
        for position, value in enumerate(node):
            yield from _leaves(value, (*path, position))
    else:
        yield path, node


def _changed_value(path, value):
    """Another valid value of the same kind as value (the leaf at path)."""
    if isinstance(value, list):
        # A longer list. The lists of scalars are required, required_fields, enum, status_codes
        # and the scopes of a security requirement; the lists of dicts are security and the
        # parts of a oneOf, anyOf or allOf.
        if value and all(isinstance(item, dict) for item in value):
            return [*value, {"type": "MUTATED"}]
        return [*value, "MUTATED"]
    if isinstance(value, bool):
        return not value
    if value is None and path[-1] == "body":
        return {"content_type": "application/json", "schema": None, "fields": {}, "required": []}
    if value is None:
        return "MUTATED"
    if isinstance(value, (int, float)):
        return value + 1
    return f"{value}X"


def _mutated(node, path, trail=()):
    """Copy of node with the leaf at path changed; only the containers on the path are copied."""
    if not path:
        return _changed_value(trail, node)
    head, rest = path[0], path[1:]
    clone = list(node) if isinstance(node, list) else dict(node)
    clone[head] = _mutated(node[head], rest, (*trail, head))
    return clone


@pytest.mark.parametrize("which", ["live index", "rich synthetic index"])
def test_diff_reports_a_change_to_every_attribute_the_index_records(which, index):
    # The rule behind the enum, items, body type, constraint and security fixes: if
    # build_index records an attribute, spec_diff must report a change to it. Change one
    # leaf of each kind (one per distinct layout position) and require a difference every
    # time. contract_sha256 is not skipped: a changed hash alone must read as a difference.
    subject = index if which == "live index" else build(rich_spec())
    first_seen = {}
    for path, value in _leaves(subject):
        if path[0] in ("source", "sha256", "op_count"):
            continue  # provenance and derived fields, printed in the report header instead
        first_seen.setdefault((_attribute_shape(path), value is None), path)
    assert len(first_seen) > (150 if which == "rich synthetic index" else 40)
    missed = []
    for (shape, _), path in sorted(first_seen.items(), key=str):
        if shape in UNDIFFED_ALONE:
            continue
        if not spec_diff.diff_indexes(subject, _mutated(subject, path)).has_differences:
            missed.append(".".join(map(str, path)))
    assert missed == []


