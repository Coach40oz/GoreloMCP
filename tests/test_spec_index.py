def _param(spec, path, method, name):
    return next(p for p in spec["paths"][path][method]["parameters"] if p["name"] == name)


def _live_diff(mutate):
    """Diff the live raw spec against a copy changed by mutate(copy), both built in memory."""
    raw = LATEST_SPEC.read_bytes()
    old_spec = json.loads(raw)
    new_spec = copy.deepcopy(old_spec)
    mutate(new_spec)
    old = spec_snapshot.build_index(old_spec, raw, "OLD")
    new = spec_snapshot.build_index(new_spec, json.dumps(new_spec).encode(), "NEW")
    result = spec_diff.diff_indexes(old, new)
    return result, spec_diff.render_markdown(result, old, new, "OLD.json", "NEW.json")


